# -*- coding: utf-8 -*-
"""
fix_lsv_remaining2.py
清理 Option A 脚本因「实际措辞与假设不一致」而漏掉的 6 处残留陈旧引用。
均为精确短语替换；full-width 括号已验证安全，短语内无引号/破折号。
"""
import shutil

SRC = r"d:\Desktop\基金经理行为分析研究\merged_manuscript.html"
BAK = SRC + ".bak_lsvfix2"
shutil.copy(SRC, BAK)
print("已备份 ->", BAK)

html = open(SRC, encoding="utf-8").read()

repls = [
    # L117 创新四：t=4.95 -> t=10.51，未来一年 -> 未来4季度
    ("未来一年的业绩（t=4.95）", "未来4季度的业绩（t=10.51）"),
    # L510 面板规模：9,581 -> 9,974
    ("包含9,581行 × 154列", "包含9,974行 × 154列"),
    # L662 核心发现2：两处 未来一年 -> 未来4季度（t 已为10.51，仅改措辞）
    ("显著预测未来一年的基金业绩（系数+0.313, t=10.51, p<0.001）",
     "显著预测未来4季度的基金业绩（系数+0.313, t=10.51, p<0.001）"),
    ("并能显著预测未来一年业绩（前向4季度，t=10.51）",
     "并能显著预测未来4季度业绩（t=10.51）"),
    # L1043 §4.16 第二：t≈4.95 -> t≈10.51，未来一年 -> 未来4季度
    ("显著预测未来一年业绩（前向4季度，t≈4.95）",
     "显著预测未来4季度业绩（t≈10.51）"),
    # L1062 本章核心结论：未来一年 -> 未来4季度；符号反转 -> 方向不稳
    ("可预测未来一年业绩", "可预测未来4季度业绩"),
    ("但其截面符号在纠正幸存者偏差后发生反转",
     "但其截面关联对样本选择高度敏感（存活为正、全样本口径方向不稳）"),
    # L1383 iFinD 交叉验证：符号反转结论 -> 方向敏感性结论（与全文修正口径一致）
    ("LSV的符号反转结论保留CSMAR口径", "LSV的方向敏感性结论保留CSMAR口径"),
]

for old, new in repls:
    c = html.count(old)
    if c != 1:
        raise SystemExit(f"[FAIL] 计数异常({c}次): {old!r}")
    html = html.replace(old, new, 1)
    print(f"[OK] {old!r}  ->  {new!r}")

open(SRC, "w", encoding="utf-8").write(html)
print("\n完成。")
