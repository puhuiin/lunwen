def norm_month_end(ds):
    y = int(ds[:4]); m = int(ds[4:6])
    d = calendar.monthrange(y, m)[1]
    return f"{y:04d}-{m:02d}-{d:02d}"

def ym_key(ds):
    return int(ds[:6])

