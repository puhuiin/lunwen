def classify(raw):
    if not isinstance(raw,str) or raw.strip()=="": return np.nan,np.nan
    s=raw.strip()
    for m in overseas_markers:
        if m in s: return "overseas",s
    best=None
    for sub,canon in sorted(aliases,key=lambda x:-len(x[0])):
        if sub in s: best=canon;break
    if best is not None:
        if best in c9: t="C9"
        elif best in set985: t="985"
        elif best in set211: t="211"
        else: t="other_domestic"
        return t,best
    return "other_domestic",s

