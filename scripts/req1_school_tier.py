m = smf.ols("ff5 ~ is_C9 + is_985 + is_211 + is_overseas + log_aum + age", data=agg).fit(cov_type='HC1')
print("\n=== OLS HC1: ff5 ~ tier dummies + log_aum + log_fund_age ===")
print("N =", int(m.nobs), " R2 =", round(m.rsquared,4))
for name in ['Intercept','is_C9','is_985','is_211','is_overseas','log_aum','age']:
    b=m.params[name]; t=m.tvalues[name]; p=m.pvalues[name]
    star="" if p>0.1 else ("*" if p>0.05 else ("**" if p>0.01 else "***"))
    print(f"  {name:12s} beta={b: .4f}  t={t: .2f}  p={p:.3f}{star}")

