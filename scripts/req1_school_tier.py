agg = panel.groupby('fund_code').agg(tier=('school_tier','first'),ff5=('ff5_adj_return','mean'),
    aum=('avg_aum','mean'),age=('log_fund_age','first')).dropna(subset=['tier','ff5','aum']).copy()
