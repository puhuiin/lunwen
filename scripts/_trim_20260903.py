saved = 0

def rep_para(key, new):
    """整段替换：从 key 起到段尾 "')"。new 为完整新段（含 para/doc 调用头）。"""
    global src, saved
    i = src.find(key)
    assert i >= 0, 'start not found: ' + key
    j = src.find("')\n", i)
    assert j > i, 'end not found: ' + key
    old = src[i:j + 2]
    saved += len(old) - len(new)
    src = src[:i] + new + src[j + 2:]
    print(f'{len(old):>5} -> {len(new):>5}  {key[:22]}')

def rep_sub(old, new):
    """子串替换（限一处）。"""
    global src, saved
    n = src.count(old)
    assert n == 1, f'count={n}: {old[:30]}'
    saved += len(old) - len(new)
    src = src.replace(old, new)

