def _cell(t):
    """矩阵单元格：方向 + 显著性星号（对应用户要求的对角线示意）。"""
    if t is None:
        return ''
    s = star(t['p'])
    if not s:
        return 'n.s.'
    return ('+' if t['t'] >= 0 else '−') + s


